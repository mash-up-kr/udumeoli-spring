-- V8: 마이페이지 "서비스 피드백 보내기"로 받은 별점 + 의견.
--   * FK 제약은 두지 않는다(V1 방침) — service_user_id는 서버가 토큰으로 확정해 넣는다.
--   * content는 최대 5,000자(한글 포함)라 VARCHAR2로는 담을 수 없어 CLOB으로 둔다.
--     Oracle STANDARD 문자열 한도는 4,000바이트고, 한글은 CHAR 시맨틱에서도 바이트 한도에 걸린다.
--   * app_version / device_info는 진단용이라 길이 때문에 피드백이 통째로 거절되면 안 된다.
--     컬럼 한도는 애플리케이션에서 잘라 맞춘다.

CREATE TABLE feedback (
    id                 NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_user_id    NUMBER(19)     NOT NULL,
    rating             NUMBER(1)      NOT NULL,
    content            CLOB           NOT NULL,
    app_version        VARCHAR2(50 CHAR)   NOT NULL,
    device_info        VARCHAR2(1000 CHAR) NOT NULL,
    created_at         TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ck_feedback_rating CHECK (rating BETWEEN 1 AND 5)
);

CREATE INDEX idx_feedback_user ON feedback (service_user_id);
