-- V9: KPI 집계용 이벤트 로그.
--   * 가입/탈퇴/파티 삭제 등은 row 자체가 사라지거나(탈퇴 시 service_user 하드 삭제) 바뀌는(멤버십 변경 등)
--     이벤트라 현재 스키마만으로는 "그날 몇 건 있었는지"를 사후에 복원할 수 없다.
--     그래서 발생 시점에 별도로 한 줄씩 남긴다. 종류별 테이블을 따로 두지 않고
--     event_type으로 구분되는 범용 테이블 하나로 둔다 — 이벤트 종류가 늘어도 집계 쿼리는 그대로다.
--   * FK 제약은 두지 않는다(V1 방침과 동일) — service_user_id는 탈퇴로 원본 행이 사라진 뒤에도 값만 남아야 한다.

CREATE TABLE kpi_event (
    id                 NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type         VARCHAR2(20)   NOT NULL,
    service_user_id    NUMBER(19)     NOT NULL,
    occurred_at        TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
    -- 이벤트별 부가정보(JSON). 예: SIGNUP의 가입 경로(provider).
    metadata           VARCHAR2(500 CHAR),
    CONSTRAINT ck_kpi_event_type CHECK (event_type IN ('SIGNUP', 'WITHDRAWAL', 'TRIP_RECORDED'))
);

-- 일자별 집계(event_type + occurred_at 범위)가 유일한 조회 경로라 이 조합 하나면 충분하다.
CREATE INDEX idx_kpi_event_type_date ON kpi_event (event_type, occurred_at);
