-- Reusable fan campaign invitation. Each fan receives a private copy of the five-person template.
CREATE TABLE campaign_party_template (
    id               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id         NUMBER(19) NOT NULL UNIQUE,
    campaign_key     VARCHAR2(40) NOT NULL UNIQUE,
    artist_name      VARCHAR2(30 CHAR) NOT NULL,
    region_code      VARCHAR2(5) NOT NULL
);

CREATE TABLE campaign_party_instance (
    id                NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_party_id NUMBER(19) NOT NULL,
    fan_user_id       NUMBER(19) NOT NULL,
    party_id          NUMBER(19) NOT NULL,
    CONSTRAINT uq_campaign_instance_fan UNIQUE (template_party_id, fan_user_id),
    CONSTRAINT uq_campaign_instance_party UNIQUE (party_id)
);

CREATE TABLE campaign_place (
    id                NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_party_id NUMBER(19) NOT NULL,
    place_order       NUMBER(2) NOT NULL,
    place_name        VARCHAR2(100 CHAR) NOT NULL,
    persona_user_id   NUMBER(19) NOT NULL,
    visit_policy      VARCHAR2(20) NOT NULL,
    CONSTRAINT ck_campaign_place_visit_policy CHECK (visit_policy IN ('PUBLIC', 'REFERENCE_ONLY')),
    CONSTRAINT uq_campaign_place_order UNIQUE (template_party_id, place_order)
);
